        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            if (_reveal.Count == 0)
                return;

            _revealClock += Math.Min(args.DeltaSeconds, 0.05f);

            for (var i = _reveal.Count - 1; i >= 0; i--)
            {
                var (control, start) = _reveal[i];
                var alpha = Math.Clamp((_revealClock - start) / RevealFade, 0f, 1f);
                control.Modulate = new Color(1f, 1f, 1f, alpha);

                if (alpha >= 1f)
                    _reveal.RemoveAt(i);
            }

            var started = (int) (_revealClock / RevealStep);
            if (started > _revealSoundIndex)
            {
                _revealSoundIndex = started;
                TerminalSounds.Play(TerminalSounds.Tick, -15f, 0.1f, 20);
            }
        }

        private void QueueReveal(Control control)
        {
            control.Modulate = new Color(1f, 1f, 1f, 0f);
            _reveal.Add((control, _reveal.Count * RevealStep));
        }

        private void RebuildAll()
        {
            var previousStation = _current?.Id;

            _stations.Clear();
            _current = null;
            _deptFilter = null;

            if (!_gameTicker.DisallowedLateJoin && _gameTicker.StationNames.Count == 0)
                _sawmill.Warning("No stations exist, nothing to display in late-join GUI");

            var departments = _prototypeManager.EnumeratePrototypes<DepartmentPrototype>().ToArray();
            Array.Sort(departments, DepartmentUIComparer.Instance);

            foreach (var (id, name) in _gameTicker.StationNames)
            {
                var view = new StationView { Id = id, Name = name };
                var available = _gameTicker.JobsAvailable[id];

                foreach (var department in departments)
                {
                    var jobs = new List<JobPrototype>();
                    foreach (var jobId in department.Roles)
                    {
                        if (!available.ContainsKey(jobId))
                            continue;

                        jobs.Add(_prototypeManager.Index<JobPrototype>(jobId));
                    }

                    // Do not display departments with no jobs available.
                    if (jobs.Count == 0)
                        continue;

                    jobs.Sort(JobUIComparer.Instance);

                    var ids = new List<string>();
                    foreach (var job in jobs)
                    {
                        if (!view.Tiles.ContainsKey(job.ID))
                        {
                            view.Tiles[job.ID] = CreateTile(id, job, available[job.ID]);
                            view.AllJobs.Add(job.ID);
                        }

                        ids.Add(job.ID);
                    }

                    view.Departments.Add((department, ids));
                }

                _stations.Add(view);
            }

            _stationRow.RemoveAllChildren();
            if (_stations.Count > 1)
            {
                foreach (var view in _stations)
                {
                    var captured = view;
                    var tab = new Button
                    {
                        Text = $"[ {view.Name} ]",
                        ToggleMode = true,
                        Group = _stationGroup,
                        StyleClasses = { StyleNano.StyleClassButtonTerminalBlackM },
                    };
                    tab.OnPressed += _ => SelectStation(captured);
                    _stationRow.AddChild(tab);
                }

                TerminalSounds.AttachAll(_stationRow);
            }

            var start = _stations.FirstOrDefault(s => s.Id == previousStation) ?? _stations.FirstOrDefault();
            if (start != null)
            {
                if (_stations.Count > 1 && _stationRow.GetChild(_stations.IndexOf(start)) is Button startTab)
                    startTab.Pressed = true;

                SelectStation(start);
            }
            else
            {
                _sidebar.RemoveAllChildren();
                _grid.RemoveAllChildren();
                _countLabel.Text = string.Empty;
            }
        }

        private void SelectStation(StationView view)
        {
            _current = view;
            _deptFilter = null;

            _sidebar.RemoveAllChildren();
            _sidebar.AddChild(new Label
            {
                Text = Loc.GetString("blackm-latejoin-departments"),
                StyleClasses = { StyleNano.StyleClassLabelTerminalBlackM },
                Margin = new Thickness(2, 0, 0, 4),
            });

            AddDepartmentButton(Loc.GetString("blackm-latejoin-all"), null, view.AllJobs.Count, true);
            foreach (var (department, jobs) in view.Departments)
            {
                AddDepartmentButton(Loc.GetString(department.Name), department.ID, jobs.Count, false);
            }

            TerminalSounds.AttachAll(_sidebar);
            RebuildGrid();
        }

        private void AddDepartmentButton(string label, string? departmentId, int count, bool pressed)
        {
            var button = new Button
            {
                Text = $"{label.ToUpperInvariant()}  [{count:00}]",
                ToggleMode = true,
                Group = _deptGroup,
                Pressed = pressed,
                HorizontalExpand = true,
                ClipText = true,
                StyleClasses = { StyleNano.StyleClassButtonTerminalBlackM },
            };

            button.OnPressed += _ =>
            {
                _deptFilter = departmentId;
                RebuildGrid();
            };

            _sidebar.AddChild(button);
        }

        private void RebuildGrid()
        {
            _grid.RemoveAllChildren();
            _reveal.Clear();
            _revealClock = 0f;
            _revealSoundIndex = 0;

            if (_current == null)
                return;

            IEnumerable<string> ids = _current.AllJobs;
            if (_deptFilter != null)
            {
                foreach (var (department, jobs) in _current.Departments)
                {
                    if (department.ID == _deptFilter)
                        ids = jobs;
                }
            }

            var count = 0;
            foreach (var id in ids)
            {
                var tile = _current.Tiles[id];
                _grid.AddChild(tile);
                QueueReveal(tile);
                count++;
            }

            _countLabel.Text = Loc.GetString("blackm-latejoin-count", ("count", count));
        }

        private JobTile CreateTile(NetEntity station, JobPrototype job, int? amount)
        {
            var name = new Label
            {
                Text = job.LocalizedName,
                ClipText = true,
                HorizontalExpand = true,
                StyleClasses = { StyleNano.StyleClassLabelTerminalBlackM },
                MouseFilter = Control.MouseFilterMode.Ignore,
            };

            var slots = new Label
            {
                FontOverride = _smallFont,
                MouseFilter = Control.MouseFilterMode.Ignore,
            };

            var icon = new TextureRect
            {
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(2, 0, 6, 0),
                MouseFilter = Control.MouseFilterMode.Ignore,
            };
            var jobIcon = _prototypeManager.Index(job.Icon);
            icon.Texture = _sprites.Frame0(jobIcon.Icon);

            var textColumn = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = Control.MouseFilterMode.Ignore,
                Children = { name, slots },
            };

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                MouseFilter = Control.MouseFilterMode.Ignore,
                Children = { icon, textColumn },
            };

            var tile = new JobTile(job.ID, slots, amount)
            {
                MinSize = new Vector2(190, 54),
                HorizontalExpand = true,
                Children = { row },
            };

            tile.OnPressed += _ => SelectedId.Invoke((station, tile.JobId));
            TerminalSounds.Attach(tile);

            if (!_jobRequirements.IsAllowed(job, (HumanoidCharacterProfile?) _preferencesManager.Preferences?.SelectedCharacter, out var reason))
            {
                tile.Disabled = true;

                if (!reason.IsEmpty)
                {
                    var tooltip = new Tooltip();
                    tooltip.SetMessage(reason);
                    tile.TooltipSupplier = _ => tooltip;
                }

                row.AddChild(new TextureRect
                {
                    TextureScale = new Vector2(0.4f, 0.4f),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    Texture = _sprites.Frame0(new SpriteSpecifier.Texture(new("/Textures/Interface/Nano/lock.svg.192dpi.png"))),
                    VerticalAlignment = VAlignment.Center,
                    MouseFilter = Control.MouseFilterMode.Ignore,
                });
            }
            else if (amount == 0)
            {
                tile.Disabled = true;
            }

            return tile;
        }

        private void JobsAvailableUpdated(IReadOnlyDictionary<NetEntity, Dictionary<ProtoId<JobPrototype>, int?>> updatedJobs)
        {
            foreach (var view in _stations)
            {
                if (!updatedJobs.TryGetValue(view.Id, out var jobsAvailable))
                    continue;

                foreach (var (jobId, tile) in view.Tiles)
                {
                    if (!jobsAvailable.TryGetValue(jobId, out var updated) || tile.Amount == updated)
                        continue;

                    tile.RefreshLabel(updated);
                    tile.Disabled |= tile.Amount == 0;
                }
            }
        }

        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);

            if (disposing)
            {
                _jobRequirements.Updated -= RebuildAll;
                _gameTicker.LobbyJobsAvailableUpdated -= JobsAvailableUpdated;
                _stations.Clear();
                _reveal.Clear();
            }
        }
    }

    sealed class JobTile : ContainerButton
    {
        private readonly Label _slots;
        private bool _initialised;

        public string JobId { get; }
        public int? Amount { get; private set; }

        public JobTile(string jobId, Label slots, int? amount)
        {
            JobId = jobId;
            _slots = slots;
            RefreshLabel(amount);
            AddStyleClass(StyleNano.StyleClassJobButtonTerminalBlackM);
            _initialised = true;
        }

        public void RefreshLabel(int? amount)
        {
            if (_initialised && Amount == amount)
                return;

            Amount = amount;

            var value = amount == null ? "--" : $"{amount:00}";
            _slots.Text = $"{Loc.GetString("blackm-latejoin-slots")} [ {value} ]";
            _slots.FontColorOverride = amount == 0
                ? Color.White.WithAlpha(0.35f)
                : StyleNano.TerminalGreen.WithAlpha(0.8f);
        }
    }
