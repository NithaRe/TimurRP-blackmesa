using Content.Client._BlackM.Achievements.UI; // BlackM
using Content.Client._BlackM.Lobby.Terminal; // BlackM
using Content.Client.Message;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Timing; // BlackM
using Robust.Shared.Prototypes;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private readonly IClientConsoleHost _consoleHost = default!;
        [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

        // BlackM start
        private LobbyGuiState _state = LobbyGuiState.Default;
        private float _styleTimer;
        private float _pulseTime;
        private AchievementsWindow? _achievementsWindow;
        // BlackM end
        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            // BlackM start
            LobbyBranding.ShaderOverride = _prototypeManager
                .Index<Robust.Client.Graphics.ShaderPrototype>("LobbyFisheye")
                .InstanceUnique();
            // BlackM end
            // BlackM start
            Menu.ConfigureOtherEntries(
                (AntagsButton, AntagsButton.Text ?? Loc.GetString("humanoid-profile-editor-antags-tab"), null),
                (OptionsButton, OptionsButton.Text ?? Loc.GetString("ui-lobby-options-button"), null),
                (AchievementsButton, AchievementsButton.Text ?? Loc.GetString("blackm-achievements-button"), null),
                (AHelpButton, AHelpButton.Text ?? Loc.GetString("ui-lobby-ahelp-button"), null),
                (CallVoteButton, CallVoteButton.Text ?? Loc.GetString("ui-vote-menu-button"), null),
                (LeaveButton, LeaveButton.Text ?? Loc.GetString("ui-lobby-leave-button"), null));
            DiscordButton.Label.Visible = false;
            BoustyButton.Label.Visible = false;
            // SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(RoundBackground, LayoutPreset.Wide);
            SetAnchorPreset(LobbyBranding, LayoutPreset.Wide);
            SetAnchorPreset(RoundBackgroundTint, LayoutPreset.Wide);
            SetAnchorPreset(LobbyVhsOverlay, LayoutPreset.Wide);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            // BlackM end

            StartTime.FontOverride = TerminalFonts.Bold(IoCManager.Resolve<Robust.Client.ResourceManagement.IResourceCache>(), 16);

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));
          //LobbyBackground.SetMarkup(Loc.GetString("")); // blackM

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            CollapseButton.OnPressed += _ => TogglePanel(false);
            ExpandButton.OnPressed += _ => TogglePanel(true);
            AchievementsButton.OnPressed += _ => ToggleAchievements(); // BlackM
            // BlackM start
            TerminalSounds.AttachAll(this);

            CharacterPreview.Hub.Activated += OnHubActivated;
            AntagsButton.OnPressed += _ => OnHubActivated("humanoid-profile-editor-antags-tab");

            StartIntro();
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            _pulseTime += args.DeltaSeconds;
            if (!ReadyButton.Pressed && !ReadyButton.Disabled)
                ReadyButton.Modulate = new Color(1f, 1f, 1f, 0.72f + 0.28f * (0.5f + 0.5f * MathF.Sin(_pulseTime * 3.2f)));
            else
                ReadyButton.Modulate = Color.White;

            _styleTimer += args.DeltaSeconds;
            if (_styleTimer < 0.25f)
                return;

            _styleTimer = 0f;
            TerminalStyler.ApplyTree(LinkBanner, true);
            TerminalStyler.ApplyTree(DevInfoBanner, true);
            TerminalSounds.AttachAll(LinkBanner);
            TerminalSounds.AttachAll(DevInfoBanner);
        }

        protected override void ExitedTree()
        {
            base.ExitedTree();

            _achievementsWindow?.Close(); // BlackM
            _achievementsWindow = null;

        }

        // BlackM: achiv
        private void ToggleAchievements()
        {
            if (_achievementsWindow is { IsOpen: true })
            {
                _achievementsWindow.Close();
                _achievementsWindow = null;
                return;
            }

            _achievementsWindow = new AchievementsWindow();
            _achievementsWindow.OpenCentered();
        }

        private void StartIntro()
        {
            Menu.PlayIntro();
            CharacterPreview.Hub.PlayIntro();
            TerminalHeader.Reveal(">> " + Loc.GetString("blackm-term-header"));
        }

        private void OnHubActivated(string? tabTitleId)
        {
            ReadyButton.Pressed = false;
            _consoleHost.ExecuteCommand("toggleready False");

            SwitchState(LobbyGuiState.CharacterSetup);

            if (tabTitleId == null)
                return;

            foreach (var child in CharacterSetupState.Children)
            {
                if (child is CharacterSetupGui setupGui)
                    setupGui.OpenSection(tabTitleId);
            }
            // BlackM end
        }

        public void SwitchState(LobbyGuiState state)
        {
            // BlackM start
            var previous = _state;
            _state = state;
            // BlackM end
            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    RightSide.Visible = true;
                    // BlackM start
                    if (previous == LobbyGuiState.CharacterSetup)
                    {
                        TerminalSounds.Play(TerminalSounds.Close);
                        Menu.PlayIntro();
                        CharacterPreview.Hub.PlayIntro();
                    }
                    // BlackM end
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;

                    var actualWidth = (float) UserInterfaceManager.RootControl.PixelWidth;
                    var setupWidth = (float) LeftSide.PixelWidth;

                    if (1 - (setupWidth / actualWidth) > 0.30)
                    {
                        RightSide.Visible = false;
                    }

                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    // BlackM start
                    if (previous != LobbyGuiState.CharacterSetup)
                    {
                        TerminalSounds.Play(TerminalSounds.Open);

                        foreach (var child in CharacterSetupState.Children)
                        {
                            if (child is CharacterSetupGui setupGui)
                                setupGui.PlayIntro();
                        }
                    }
                    // BlackM end

                    break;
            }
        }

        private void TogglePanel(bool value)
        {
            RightSide.Visible = value;
            ExpandPanel.Visible = !value;
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
