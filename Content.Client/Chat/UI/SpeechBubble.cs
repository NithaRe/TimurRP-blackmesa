            _iconRects.Add(texRect);

            return new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 4,
                VerticalAlignment = VAlignment.Center,
                Children =
                {
                    texRect,
                    content,
                }
            };
        } // BlackM: Wrap content with icon in a horizontal BoxContainer

        // BlackM start
        private OutlinedText? _text;
        private int _revealed;
        private float _typewriterAccumulated;
        private bool _typewriterActive;

        private const float ShakeAmplitude = 1.5f;
        private const float ShakeInterval = 0.04f;
        private bool _shake;
        private float _shakeTimer;
        private Vector2 _shakeOffset;
        private readonly Random _shakeRandom = new();

        private static readonly Regex BbTagRegex =
            new(@"\[/?[a-zA-Z][a-zA-Z0-9]*(=(""[^""]*""|[^\]\s]+))?(\s+[a-zA-Z0-9]+=(""[^""]*""|[^\]\s]+))*\]", RegexOptions.Compiled);

        private static float GetOutlineThickness(int fontSize)
        {
            return fontSize * 96f / 72f / DesignPixelsPerEm * OutlineScale;
        }

        private Font? GetBubbleFont(int size)
        {
            if (BubbleFonts.TryGetValue(size, out var cached))
                return cached;

            Font? font = null;
            try
            {
                var res = _resourceCache.GetResource<FontResource>(new ResPath(BubbleFontPath));
                font = new VectorFont(res, size);
            }
            catch (Exception e)
            {
            }

            BubbleFonts[size] = font;
            return font;
        }

        protected static bool IsYell(ChatMessage message)
        {
            var wrapped = message.WrappedMessage;
            var headerEnd = wrapped.IndexOf("[/BubbleHeader]", StringComparison.Ordinal);
            if (headerEnd >= 0)
                wrapped = wrapped.Substring(headerEnd);

            return wrapped.Contains("[bold]", StringComparison.Ordinal) ||
                   wrapped.Contains("[bolditalic]", StringComparison.Ordinal);
        }

        protected Control BuildTextBubble(string markup, Color? fontColor, Texture? icon, bool typewriter, string speechStyleClass, string? speakerName = null, bool yell = false)
        {
            var whisper = speechStyleClass == "whisperBox";
            var emote = speechStyleClass == "emoteBox";
            var looc = speechStyleClass == "loocBox";

            yell = yell && typewriter && !whisper && !emote && !looc;
            _shake = yell;

            Color color;
            if (whisper)
                color = WhisperColor;
            else if (yell)
                color = YellColor;
            else if (looc)
                color = LoocColor;
            else if (emote)
                color = EmoteColor;
            else
                color = fontColor ?? GetPlayerSpeechColor(speakerName);

            var plain = BbTagRegex.Replace(markup, string.Empty)
                .Replace("\\[", "[")
                .Replace("\\]", "]")
                .Trim();

            if (emote && !plain.StartsWith('*'))
                plain = "*" + plain + "*";
            else if (whisper)
                plain = "..." + plain + "...";

            var outline = OutlineColor;
            var size = BubbleFontSize;

            if (yell)
            {
                size = BubbleFontSize + YellFontSizeDelta;
            }
            else if (whisper)
            {
                size = Math.Max(BubbleFontSize - WhisperFontSizeDelta, 6);
                color = color.WithAlpha(WhisperAlpha);
                outline = outline.WithAlpha(WhisperAlpha * 0.8f);
            }

            _text = new OutlinedText(plain, GetBubbleFont(size), color, outline, GetOutlineThickness(size), SpeechMaxWidth, !typewriter);

            _revealed = 0;
            _typewriterAccumulated = 0f;
            _typeInterval = SpeechBarksSystem.GetTypeInterval(_text.TotalLength);
            _typewriterActive = typewriter && _text.TotalLength > 0;

            return WrapWithIcon(_text, icon);
        }

        private Color GetPlayerSpeechColor(string? speakerName)
        {
            if (!string.IsNullOrWhiteSpace(speakerName))
                speakerName = BbTagRegex.Replace(speakerName, string.Empty).Trim();

            if (string.IsNullOrWhiteSpace(speakerName))
                speakerName = Identity.Name(_senderEntity, _entityManager);

            if (string.IsNullOrWhiteSpace(speakerName))
                speakerName = _entityManager.GetNetEntity(_senderEntity).Id.ToString();

            var hash = 2166136261u;
            foreach (var character in speakerName)
            {
                hash ^= character;
                hash *= 16777619;
            }

            hash ^= hash >> 16;
            hash *= 0x85ebca6bu;
            hash ^= hash >> 13;
            hash *= 0xc2b2ae35u;
            hash ^= hash >> 16;

            var hue = (hash % 360) / 360f;
            var saturation = 0.55f + ((hash >> 9) % 4) * 0.1f;
            var lightness = 0.62f + ((hash >> 13) % 3) * 0.06f;

            return Color.FromHsl(new Vector4(hue, saturation, lightness, 1f));
        }

        private void UpdateTypewriter(float deltaSeconds)
        {
            if (!_typewriterActive || _text == null)
                return;

            if (_revealed >= _text.TotalLength)
            {
                _typewriterActive = false;
                return;
            }

            _typewriterAccumulated += deltaSeconds;

            while (_typewriterAccumulated >= _typeInterval && _revealed < _text.TotalLength)
            {
                _typewriterAccumulated -= _typeInterval;
                _deathTime += TimeSpan.FromSeconds(_typeInterval);
                _revealed++;
            }

            _text.SetRevealed(_revealed);

            if (_revealed >= _text.TotalLength)
                _typewriterActive = false;
        }
        // BlackM end

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            // BlackM
            var deathTime = _deathTime > _soundHoldUntil ? _deathTime : _soundHoldUntil;
            var timeLeft = (float)(deathTime - _timing.RealTime).TotalSeconds;
            if (_entityManager.Deleted(_senderEntity) || timeLeft <= 0)
            {
                // Timer spawn to prevent concurrent modification exception.
                Timer.Spawn(0, Die);
                return;
            }

            // Lerp to our new vertical offset if it's been modified.
            if (MathHelper.CloseToPercent(_verticalOffsetAchieved - VerticalOffset, 0, 0.1))
            {
                _verticalOffsetAchieved = VerticalOffset;
            }
            else
            {
                _verticalOffsetAchieved = MathHelper.Lerp(_verticalOffsetAchieved, VerticalOffset, 10 * args.DeltaSeconds);
            }

            if (!_entityManager.TryGetComponent<TransformComponent>(_senderEntity, out var xform) || xform.MapID != _eyeManager.CurrentEye.Position.MapId)
            {
                Modulate = Color.White.WithAlpha(0);
                return;
            }

            UpdateTypewriter(args.DeltaSeconds); // BlackM

            var fadeIn = Math.Clamp((float) (_timing.RealTime - _spawnTime).TotalSeconds / FadeInTime, 0f, 1f);

            if (timeLeft <= FadeTime.TotalSeconds)
            {
                // Update alpha if we're fading.
                Modulate = Color.White.WithAlpha(fadeIn * timeLeft / (float)FadeTime.TotalSeconds);
            }
            else
            {
                // Make opaque otherwise, because it might have been hidden before
                Modulate = Color.White.WithAlpha(fadeIn);
            }

            var baseOffset = 0f;

            if (_entityManager.TryGetComponent<SpeechComponent>(_senderEntity, out var speech))
                baseOffset = speech.SpeechBubbleOffset;

            var offset = (-_eyeManager.CurrentEye.Rotation).ToWorldVec() * -(EntityVerticalOffset + baseOffset);
            var worldPos = _transformSystem.GetWorldPosition(xform) + offset;

            var lowerCenter = _eyeManager.WorldToScreen(worldPos) / UIScale;
            var screenPos = lowerCenter - new Vector2(ContentSize.X / 2, ContentSize.Y + _verticalOffsetAchieved);
            // Round to nearest 0.5
            screenPos = (screenPos * 2).Rounded() / 2;
            // BlackM start
            if (_shake)
            {
                _shakeTimer += args.DeltaSeconds;
                if (_shakeTimer >= ShakeInterval)
                {
                    _shakeTimer = 0f;
                    _shakeOffset = new Vector2(
                        (float)(_shakeRandom.NextDouble() * 2 - 1) * ShakeAmplitude,
                        (float)(_shakeRandom.NextDouble() * 2 - 1) * ShakeAmplitude);
                }

                screenPos += _shakeOffset;
            }
            // BlackM end
            LayoutContainer.SetPosition(this, screenPos);

            var height = MathF.Ceiling(MathHelper.Clamp(lowerCenter.Y - screenPos.Y, 0, ContentSize.Y));
            SetHeight = height;
        }

        private void Die()
        {
            if (Disposed)
            {
                return;
            }

            OnDied?.Invoke(_senderEntity, this);
        }

        // BlackM
        public void HoldUntilSoundEnds(TimeSpan duration)
        {
            var until = _timing.RealTime + duration + FadeTime;
            if (until > _soundHoldUntil)
                _soundHoldUntil = until;
        }

        /// <summary>
        ///     Causes the speech bubble to start fading IMMEDIATELY.
        /// </summary>
        public void FadeNow()
        {
            // BlackM
            var effective = _deathTime > _soundHoldUntil ? _deathTime : _soundHoldUntil;
            _soundHoldUntil = TimeSpan.Zero;

            if (effective > _timing.RealTime)
            {
                _deathTime = _timing.RealTime + FadeTime;
            }
        }

        protected FormattedMessage FormatSpeech(string message, Color? fontColor = null)
        {
            var msg = new FormattedMessage();
            if (fontColor != null)
                msg.PushColor(fontColor.Value);
            msg.AddMarkupOrThrow(message);
            return msg;
        }

        protected FormattedMessage ExtractAndFormatSpeechSubstring(ChatMessage message, string tag, Color? fontColor = null)
        {
            return FormatSpeech(SharedChatSystem.GetStringInsideTag(message, tag), fontColor);
        }

