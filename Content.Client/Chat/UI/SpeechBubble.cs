        public static SpeechBubble CreateSpeechBubble(SpeechType type, ChatMessage message, EntityUid senderEntity, Texture? icon = null) // BlackM: Added icon parameter
        {
            switch (type)
            {
                case SpeechType.Emote:
                    return new TextSpeechBubble(message, senderEntity, "emoteBox", icon: icon); // BlackM: Pass icon to TextSpeechBubble

                case SpeechType.Say:
                    return new FancyTextSpeechBubble(message, senderEntity, "sayBox", icon: icon); // BlackM: Pass icon to FancyTextSpeechBubble

                case SpeechType.Whisper:
                    return new FancyTextSpeechBubble(message, senderEntity, "whisperBox", icon: icon); // BlackM: Pass icon to FancyTextSpeechBubble

                case SpeechType.Looc:
                    return new TextSpeechBubble(message, senderEntity, "emoteBox", Color.FromHex("#48d1cc"), icon); // BlackM: Pass icon to TextSpeechBubble

                default:
                    throw new ArgumentOutOfRangeException();
            }
        }

        private readonly List<TextureRect> _iconRects = new(); // BlackM: Store references to icon TextureRects for later updates

        public SpeechBubble(ChatMessage message, EntityUid senderEntity, string speechStyleClass, Color? fontColor = null, Texture? icon = null) // BlackM: Added icon parameter
        {
            IoCManager.InjectDependencies(this);
            _senderEntity = senderEntity;
            _transformSystem = _entityManager.System<SharedTransformSystem>();

            // Use text clipping so new messages don't overlap old ones being pushed up.
            RectClipContent = true;

            Control? bubble = null; // BlackM: Declare bubble variable here so we can access it in the icon callback

            if (icon == null)
            {
                icon = PhraseWheelIconRegistry.TryTake(_senderEntity, _timing.CurTime, texture =>
                {
                    foreach (var rect in _iconRects)
                    {
                        rect.Texture = texture;
                        rect.Visible = true;
                    }

                    if (bubble != null)
                    {
                        bubble.Measure(Vector2Helpers.Infinity);
                        ContentSize = bubble.DesiredSize;
                        _verticalOffsetAchieved = VerticalOffset; // BlackM
                    }
                });
            }

            bubble = BuildBubble(message, speechStyleClass, fontColor, icon); // BlackM: Pass icon to BuildBubble

            AddChild(bubble);

            ForceRunStyleUpdate();

            bubble.Measure(Vector2Helpers.Infinity);
            ContentSize = bubble.DesiredSize;
            _verticalOffsetAchieved = VerticalOffset; // BlackM
            _deathTime = _timing.RealTime + TotalTime;
            _spawnTime = _timing.RealTime;

            // BlackM
            var holdDuration = PhraseWheelIconRegistry.TryTakeSoundDuration(_senderEntity, _timing.CurTime, HoldUntilSoundEnds);
            if (holdDuration != null)
                HoldUntilSoundEnds(holdDuration.Value);
        }

        protected abstract Control BuildBubble(ChatMessage message, string speechStyleClass, Color? fontColor = null, Texture? icon = null); // BlackM: Added icon parameter

        protected Control WrapWithIcon(Control content, Texture? icon)
        {
            var texRect = new TextureRect
            {
                Texture = icon,
                MinSize = new Vector2(20, 20),
                MaxSize = new Vector2(20, 20),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
                Visible = icon != null
            };

            _iconRects.Add(texRect);

            return new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 4,
                VerticalAlignment = VAlignment.Center,
                Children =
                {
                    texRect,
                    content,
                }
            };
        } // BlackM: Wrap content with icon in a horizontal BoxContainer

        // BlackM start
        private OutlinedText? _text;
        private int _revealed;
        private float _typewriterAccumulated;
        private bool _typewriterActive;

        private const float ShakeAmplitude = 1.5f;
        private const float ShakeInterval = 0.04f;
        private bool _shake;
        private float _shakeTimer;
        private Vector2 _shakeOffset;
        private readonly Random _shakeRandom = new();

        private static readonly Regex BbTagRegex =
            new(@"\[/?[a-zA-Z][a-zA-Z0-9]*(=(""[^""]*""|[^\]\s]+))?(\s+[a-zA-Z0-9]+=(""[^""]*""|[^\]\s]+))*\]", RegexOptions.Compiled);

        private static readonly Regex ColorTagRegex =
            new(@"\[color=(?:""([^""]*)""|([^\]\s]+))\]", RegexOptions.Compiled);

        private Font? GetBubbleFont(int size)
        {
            if (BubbleFonts.TryGetValue(size, out var cached))
                return cached;

            Font? font = null;
            try
            {
                var res = _resourceCache.GetResource<FontResource>(new ResPath(BubbleFontPath));
                font = new VectorFont(res, size);
            }
            catch (Exception e)
            {
            }

            BubbleFonts[size] = font;
            return font;
        }

        protected Control BuildTextBubble(string markup, Color? fontColor, Texture? icon, bool typewriter, string speechStyleClass)
        {
            var whisper = speechStyleClass == "whisperBox";
            var emote = speechStyleClass == "emoteBox" && fontColor == null;

            var color = Color.White;
            var colorMatch = ColorTagRegex.Match(markup);
            if (colorMatch.Success)
            {
                var value = colorMatch.Groups[1].Success ? colorMatch.Groups[1].Value : colorMatch.Groups[2].Value;
                if (Color.TryParse(value, out var parsed))
                    color = parsed;
            }

            if (typewriter)
                _shake = markup.Contains("[bold]", StringComparison.Ordinal);

            if (fontColor != null)
                color = fontColor.Value;
            else if (emote)
                color = EmoteColor;
            else if (whisper)
                color = WhisperColor;
            else if (_shake)
                color = YellColor;

            var plain = BbTagRegex.Replace(markup, string.Empty)
                .Replace("\\[", "[")
                .Replace("\\]", "]")
                .Trim();

            if (emote && !plain.StartsWith('*'))
                plain = "*" + plain + "*";
            else if (whisper)
                plain = "..." + plain + "...";

            var outline = OutlineColor;
            var size = BubbleFontSize;

            if (whisper)
            {
                size = Math.Max(BubbleFontSize - WhisperFontSizeDelta, 6);
                color = color.WithAlpha(WhisperAlpha);
                outline = outline.WithAlpha(WhisperAlpha * 0.8f);
            }

            _text = new OutlinedText(plain, GetBubbleFont(size), color, outline, SpeechMaxWidth, !typewriter);

            _revealed = 0;
            _typewriterAccumulated = 0f;
            _typeInterval = SpeechBarksSystem.GetTypeInterval(_text.TotalLength);
            _typewriterActive = typewriter && _text.TotalLength > 0;

            var inner = WrapWithIcon(_text, icon);

            // blackm
            var boxAlpha = whisper ? BoxAlpha * 0.8f : BoxAlpha;
            var borderAlpha = whisper ? BoxBorderAlpha * 0.8f : BoxBorderAlpha;

            return new PanelContainer
            {
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = BoxColor.WithAlpha(boxAlpha),
                    BorderColor = color.WithAlpha(borderAlpha),
                    BorderThickness = new Thickness(1),
                    ContentMarginLeftOverride = BoxPaddingX,
                    ContentMarginRightOverride = BoxPaddingX,
                    ContentMarginTopOverride = BoxPaddingY,
                    ContentMarginBottomOverride = BoxPaddingY,
                },
                Children = { inner },
            };
        }

        private void UpdateTypewriter(float deltaSeconds)
        {
            if (!_typewriterActive || _text == null)
                return;

            if (_revealed >= _text.TotalLength)
            {
                _typewriterActive = false;
                return;
            }

            _typewriterAccumulated += deltaSeconds;

            while (_typewriterAccumulated >= _typeInterval && _revealed < _text.TotalLength)
            {
                _typewriterAccumulated -= _typeInterval;
                _deathTime += TimeSpan.FromSeconds(_typeInterval);
                _revealed++;
            }

            _text.SetRevealed(_revealed);

            if (_revealed >= _text.TotalLength)
                _typewriterActive = false;
        }
        // BlackM end

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            // BlackM
            var deathTime = _deathTime > _soundHoldUntil ? _deathTime : _soundHoldUntil;
            var timeLeft = (float)(deathTime - _timing.RealTime).TotalSeconds;
            if (_entityManager.Deleted(_senderEntity) || timeLeft <= 0)
            {
                // Timer spawn to prevent concurrent modification exception.
                Timer.Spawn(0, Die);
                return;
            }

            // Lerp to our new vertical offset if it's been modified.
            if (MathHelper.CloseToPercent(_verticalOffsetAchieved - VerticalOffset, 0, 0.1))
            {
                _verticalOffsetAchieved = VerticalOffset;
            }
            else
            {
                _verticalOffsetAchieved = MathHelper.Lerp(_verticalOffsetAchieved, VerticalOffset, 10 * args.DeltaSeconds);
            }

            if (!_entityManager.TryGetComponent<TransformComponent>(_senderEntity, out var xform) || xform.MapID != _eyeManager.CurrentEye.Position.MapId)
            {
                Modulate = Color.White.WithAlpha(0);
                return;
            }

            UpdateTypewriter(args.DeltaSeconds); // BlackM

            var fadeIn = Math.Clamp((float) (_timing.RealTime - _spawnTime).TotalSeconds / FadeInTime, 0f, 1f);

            if (timeLeft <= FadeTime.TotalSeconds)
            {
                // Update alpha if we're fading.
                Modulate = Color.White.WithAlpha(fadeIn * timeLeft / (float)FadeTime.TotalSeconds);
            }
            else
            {
                // Make opaque otherwise, because it might have been hidden before
                Modulate = Color.White.WithAlpha(fadeIn);
            }

            var baseOffset = 0f;

            if (_entityManager.TryGetComponent<SpeechComponent>(_senderEntity, out var speech))
                baseOffset = speech.SpeechBubbleOffset;

            var offset = (-_eyeManager.CurrentEye.Rotation).ToWorldVec() * -(EntityVerticalOffset + baseOffset);
            var worldPos = _transformSystem.GetWorldPosition(xform) + offset;

            var lowerCenter = _eyeManager.WorldToScreen(worldPos) / UIScale;
            var screenPos = lowerCenter - new Vector2(ContentSize.X / 2, ContentSize.Y + _verticalOffsetAchieved);
            // Round to nearest 0.5
            screenPos = (screenPos * 2).Rounded() / 2;
            // BlackM start
            if (_shake)
            {
                _shakeTimer += args.DeltaSeconds;
                if (_shakeTimer >= ShakeInterval)
                {
                    _shakeTimer = 0f;
                    _shakeOffset = new Vector2(
                        (float)(_shakeRandom.NextDouble() * 2 - 1) * ShakeAmplitude,
                        (float)(_shakeRandom.NextDouble() * 2 - 1) * ShakeAmplitude);
                }

                screenPos += _shakeOffset;
            }
            // BlackM end
            LayoutContainer.SetPosition(this, screenPos);

            var height = MathF.Ceiling(MathHelper.Clamp(lowerCenter.Y - screenPos.Y, 0, ContentSize.Y));
            SetHeight = height;
        }

        private void Die()
        {
            if (Disposed)
            {
                return;
            }

            OnDied?.Invoke(_senderEntity, this);
        }

        // BlackM
        public void HoldUntilSoundEnds(TimeSpan duration)
        {
            var until = _timing.RealTime + duration + FadeTime;
            if (until > _soundHoldUntil)
                _soundHoldUntil = until;
        }

        /// <summary>
        ///     Causes the speech bubble to start fading IMMEDIATELY.
        /// </summary>
        public void FadeNow()
        {
            // BlackM
            var effective = _deathTime > _soundHoldUntil ? _deathTime : _soundHoldUntil;
            _soundHoldUntil = TimeSpan.Zero;

            if (effective > _timing.RealTime)
            {
                _deathTime = _timing.RealTime + FadeTime;
            }
        }

        protected FormattedMessage FormatSpeech(string message, Color? fontColor = null)
        {
            var msg = new FormattedMessage();
            if (fontColor != null)
                msg.PushColor(fontColor.Value);
            msg.AddMarkupOrThrow(message);
            return msg;
        }

        protected FormattedMessage ExtractAndFormatSpeechSubstring(ChatMessage message, string tag, Color? fontColor = null)
        {
            return FormatSpeech(SharedChatSystem.GetStringInsideTag(message, tag), fontColor);
        }

