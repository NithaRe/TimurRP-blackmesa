using Content.Shared._BlackM.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client._BlackM.DiscordAuth;

[GenerateTypedNameReferences]
public sealed partial class DiscordAuthGui : Control
{
    [Dependency] private Content.Corvax.Interfaces.Client.IClientDiscordAuthManager _discordAuthManager = default!;
    [Dependency] private IClientConsoleHost _consoleHost = default!;
    [Dependency] private IConfigurationManager _cfg = default!;

    public DiscordAuthGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        LayoutContainer.SetAnchorPreset(this, LayoutContainer.LayoutPreset.Wide);

        if (!_discordAuthManager.IsOpt)
        {
            ByPassBtn.Visible = false;
        }
        else
        {
            ByPassBtn.OnPressed += _ => _discordAuthManager.ByPass();
        }

        QuitButton.OnPressed += _ => _consoleHost.ExecuteCommand("quit");

        OpenServerButton.OnPressed += _ =>
        {
            var url = _cfg.GetCVar(BlackMCVars.DiscordAuthInviteUrl);
            if (url.StartsWith("https://"))
                IoCManager.Resolve<IUriOpener>().OpenUri(url);
        };

        RefreshData();
        _discordAuthManager.DataUpdated += RefreshData;
    }

    private void RefreshData()
    {
        var hasCode = _discordAuthManager.LinkCode != string.Empty;

        LinkInfoLabel.Text = hasCode
            ? "Зайдите на наш Discord-сервер, введите команду /verify и этот код:"
            : "Получаем код...";

        CodeEdit.TextRope = new Rope.Leaf(hasCode ? _discordAuthManager.LinkCode : "...");
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
        {
            _discordAuthManager.DataUpdated -= RefreshData;
        }
    }
}