using System.Numerics;
using Content.Shared._BlackM.Lobby;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Map;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using CameraEye = Robust.Shared.Graphics.Eye;

namespace Content.Client._BlackM.Lobby.Terminal;


[GenerateTypedNameReferences]
public sealed partial class LobbyRoundBackground : Control
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IEntitySystemManager _entitySystemManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private LobbyRoundCameraSystem? _cameraSystem;
    private NetEntity? _pendingCamera;
    private EntityUid? _activeCamera;
    private CameraEye? _cameraEye;

    public LobbyRoundBackground()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RoundView.PostProcessShader = _prototypeManager.Index<Robust.Client.Graphics.ShaderPrototype>("LobbyFisheye").InstanceUnique();
        RoundView.Visible = false;
        Fallback.Visible = true;
        RoundView.OnResized += UpdateViewportSize;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        UpdateViewportSize();
    }

    protected override void ExitedTree()
    {
        if (_cameraSystem != null)
            _cameraSystem.CameraChanged -= SetCamera;
        _cameraSystem = null;
        RoundView.Eye = null;
        _activeCamera = null;
        base.ExitedTree();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_cameraSystem == null && _entitySystemManager.TryGetEntitySystem<LobbyRoundCameraSystem>(out var cameraSystem))
        {
            _cameraSystem = cameraSystem;
            _cameraSystem.CameraChanged += SetCamera;
            SetCamera(_cameraSystem.Camera);
        }

        if (_pendingCamera is not { } netCamera || !_entityManager.TryGetEntity(netCamera, out var camera))
            return;

        if (!_entityManager.TryGetComponent<EyeComponent>(camera, out var eye))
            return;

        _activeCamera = camera;
        if (_cameraEye == null)
        {
            _cameraEye = new CameraEye
            {
                Position = eye.Eye.Position,
                Rotation = eye.Eye.Rotation,
                Zoom = eye.Eye.Zoom,
                Offset = eye.Eye.Offset,
                DrawFov = eye.Eye.DrawFov,
                DrawLight = eye.Eye.DrawLight,
            };
            RoundView.Eye = _cameraEye;
        }

        var targetEye = eye.Eye;
        var blend = 1f - MathF.Exp(-4f * args.DeltaSeconds);
        if (_cameraEye.Position.MapId != targetEye.Position.MapId)
            _cameraEye.Position = targetEye.Position;
        else
            _cameraEye.Position = new MapCoordinates(
                Vector2.Lerp(_cameraEye.Position.Position, targetEye.Position.Position, blend),
                targetEye.Position.MapId);

        _cameraEye.Zoom = targetEye.Zoom;
        _cameraEye.Offset = targetEye.Offset;
        _cameraEye.DrawFov = targetEye.DrawFov;
        _cameraEye.DrawLight = targetEye.DrawLight;

        if (_entitySystemManager.TryGetEntitySystem<SharedTransformSystem>(out var transformSystem) &&
            _entityManager.TryGetComponent<TransformComponent>(camera, out var cameraTransform))
        {
            var targetRotation = cameraTransform.GridUid is { } grid &&
                                 _entityManager.TryGetComponent<TransformComponent>(grid, out _)
                ? -transformSystem.GetWorldRotation(grid)
                : Angle.Zero;
            _cameraEye.Rotation += Angle.ShortestDistance(_cameraEye.Rotation, targetRotation) * blend;
        }
    }

    private void SetCamera(NetEntity? camera)
    {
        _pendingCamera = camera;
        _activeCamera = null;
        RoundView.Eye = null;
        _cameraEye = null;
        RoundView.Visible = camera != null;
        Fallback.Visible = camera == null;
    }

    private void UpdateViewportSize()
    {
        RoundView.ViewportSize = new Vector2i(Math.Max(RoundView.PixelWidth, 100),
            Math.Max(RoundView.PixelHeight, 100));
    }
}
