namespace Content.Client._BlackM.Ams;

[GenerateTypedNameReferences]
public sealed partial class AmsWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IResourceCache _cache = default!;
    [Dependency] private readonly IEntityManager _entMan = default!;

    private const string UiDir = "/Textures/_BlackM/Interface/Ams/";
    private const string PartsRsiPath = "/Textures/_BlackM/Objects/ams_parts.rsi";

    private static readonly Color Gray = Color.FromHex("#6c8791");
    private static readonly Color Cyan = Color.FromHex("#4fd8ff");
    private static readonly Color Green = Color.FromHex("#7dff6a");
    private static readonly Color Red = Color.FromHex("#ff4a40");
    private static readonly Color Text = Color.FromHex("#dfe8ec");

    public event Action? OnLaunch;

    private sealed class PartCard(PanelContainer panel, Label state, TextureRect mark)
    {
        public readonly PanelContainer Panel = panel;
        public readonly Label State = state;
        public readonly TextureRect Mark = mark;
        public bool? Filled;
    }

    private readonly Dictionary<string, PartCard> _cards = new();
    private readonly Texture _check;
    private readonly Texture _cross;
    private AmsBuiState? _state;
    private AmsStatus? _lastStatus;
    private Color? _buttonColor;

    public AmsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _check = Tex("check.png");
        _cross = Tex("cross.png");

        RootPanel.PanelOverride = Patch("frame.png", 14);
        HeaderPanel.PanelOverride = Patch("header.png", 6);

        Logo.Texture = Tex("lambda.png");
        Logo.TextureScale = new Vector2(2f, 2f);

        Hazard.Texture = Tex("hazard.png");
        Hazard.Stretch = TextureRect.StretchMode.Tile;
        Hazard.MinSize = new Vector2(0, 8);

        ChargeBar.BackgroundStyleBoxOverride = Patch("bar_bg.png", 4);

        ActionButton.OnPressed += _ => OnLaunch?.Invoke();
    }

    private Texture Tex(string file)
    {
        return _cache.GetResource<TextureResource>(UiDir + file).Texture;
    }

    private StyleBoxTexture Patch(string file, float margin, Color? tint = null)
    {
        var box = new StyleBoxTexture
        {
            Texture = Tex(file),
            Modulate = tint ?? Color.White,
        };
        box.SetPatchMargin(StyleBox.Margin.All, margin);
        return box;
    }

    public void UpdateState(AmsBuiState state)
    {
        _state = state;

        if (_cards.Count == 0)
        {
            var sprite = _entMan.System<SpriteSystem>();

            foreach (var id in state.AllSlots)
            {
                var icon = sprite.Frame0(new SpriteSpecifier.Rsi(new ResPath(PartsRsiPath), id.Replace("ams_part_", "")));

                var iconRect = new TextureRect
                {
                    Texture = icon,
                    TextureScale = new Vector2(1.5f, 1.5f),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    MinSize = new Vector2(48, 48),
                    VerticalAlignment = Control.VAlignment.Center,
                };

                var name = new Label
                {
                    Text = Loc.GetString(id.Replace('_', '-')),
                    ClipText = true,
                    FontColorOverride = Text,
                };

                var status = new Label();
                status.StyleClasses.Add("LabelSubText");

                var texts = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    HorizontalExpand = true,
                    VerticalAlignment = Control.VAlignment.Center,
                };
                texts.AddChild(name);
                texts.AddChild(status);

                var mark = new TextureRect
                {
                    TextureScale = new Vector2(1.5f, 1.5f),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    MinSize = new Vector2(24, 24),
                    VerticalAlignment = Control.VAlignment.Center,
                };

                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(12, 8, 10, 8),
                    SeparationOverride = 8,
                };
                row.AddChild(iconRect);
                row.AddChild(texts);
                row.AddChild(mark);

                var panel = new PanelContainer { HorizontalExpand = true };
                panel.AddChild(row);

                _cards[id] = new PartCard(panel, status, mark);
                PartsGrid.AddChild(panel);
            }
        }

        foreach (var id in state.AllSlots)
        {
            if (!_cards.TryGetValue(id, out var card))
                continue;

            var filled = state.FilledSlots.Contains(id);
            if (card.Filled == filled)
                continue;

            var color = filled ? Green : Gray;
            card.Filled = filled;
            card.State.Text = Loc.GetString(filled ? "ams-ui-part-installed" : "ams-ui-part-missing");
            card.State.FontColorOverride = color;
            card.Mark.Texture = filled ? _check : _cross;
            card.Mark.Modulate = color;
            card.Panel.PanelOverride = Patch("slot.png", 10, color);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state is not { } s)
            return;

        var now = _timing.CurTime;
        var key = s.Status.ToString().ToLowerInvariant();
        var color = StatusColor(s.Status);

        if (_lastStatus != s.Status)
        {
            _lastStatus = s.Status;
            StatusLabel.Text = Loc.GetString($"ams-ui-status-{key}");
            StatusLabel.FontColorOverride = color;
            HintLabel.Text = Loc.GetString($"ams-ui-hint-{key}");
            ChargeBar.ForegroundStyleBoxOverride = Patch("bar_fill.png", 4, color);
        }

        TimeSpan? remaining = s.Status switch
        {
            AmsStatus.Synchronizing when s.SyncStartTime is { } start => start + TimeSpan.FromSeconds(s.ChargeTime) - now,
            AmsStatus.Active => s.ActiveEndTime - now,
            AmsStatus.Detonating => s.DetonationTime - now,
            _ => null,
        };

        if (remaining is { } r)
        {
            if (r < TimeSpan.Zero)
                r = TimeSpan.Zero;

            TimerLabel.Text = $"{(int) r.TotalMinutes:00}:{r.Seconds:00}";
            TimerLabel.FontColorOverride = color;
        }
        else
        {
            TimerLabel.Text = string.Empty;
        }

        var charge = AmsHelpers.GetCharge(s.Status, s.SyncStartTime, s.ChargeTime, now);
        ChargeBar.Value = charge;
        ChargeLabel.Text = $"{(int) (charge * 100)}%";

        var allFilled = s.AllSlots.Count > 0 && s.FilledSlots.Count >= s.AllSlots.Count;

        string text;
        bool enabled;
        Color buttonColor;

        switch (s.Status)
        {
            case AmsStatus.Inactive:
                enabled = allFilled;
                text = Loc.GetString(allFilled ? "ams-ui-btn-start-sync" : "ams-ui-btn-need-parts");
                buttonColor = allFilled ? Cyan : Gray;
                break;
            case AmsStatus.Ready:
                enabled = true;
                text = Loc.GetString("ams-ui-btn-activate");
                buttonColor = Green;
                break;
            default:
                enabled = false;
                text = Loc.GetString($"ams-ui-btn-{key}");
                buttonColor = s.Status == AmsStatus.Detonating ? Red : Gray;
                break;
        }

        ActionButton.Text = text;
        ActionButton.Disabled = !enabled;
        ActionButton.ModulateSelfOverride = enabled ? null : Color.White.WithAlpha(0.6f);

        if (_buttonColor != buttonColor)
        {
            _buttonColor = buttonColor;
            ActionButton.StyleBoxOverride = Patch("button.png", 6, buttonColor);
        }
    }

    private static Color StatusColor(AmsStatus status) => status switch
    {
        AmsStatus.Synchronizing => Cyan,
        AmsStatus.Ready or AmsStatus.Active => Green,
        AmsStatus.Detonating => Red,
        _ => Gray,
    };
}
