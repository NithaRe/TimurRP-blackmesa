namespace Content.Client._BlackM.Ams;

[GenerateTypedNameReferences]
public sealed partial class AmsWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IEntityManager _entMan = default!;

    private const string PartsRsiPath = "/Textures/_BlackM/Objects/ams_parts.rsi";

    private static readonly Color Neutral = Color.FromHex("#8d8d96");
    private static readonly Color Warning = Color.FromHex("#e0a040");
    private static readonly Color Info = Color.FromHex("#5fc8f0");
    private static readonly Color Good = Color.FromHex("#5bd35b");
    private static readonly Color Danger = Color.FromHex("#e04a40");

    private static readonly Color PanelBg = Color.FromHex("#1b1b1f");
    private static readonly Color CardBg = Color.FromHex("#232328");
    private static readonly Color Border = Color.FromHex("#3a3a42");

    public event Action? OnLaunch;
    public event Action<string>? OnLever;

    private sealed class PartCard(PanelContainer panel, Label state, ProgressBar progress, Button lever)
    {
        public readonly PanelContainer Panel = panel;
        public readonly Label State = state;
        public readonly ProgressBar Progress = progress;
        public readonly Button Lever = lever;
        public Color? Color;
    }

    private readonly Dictionary<string, PartCard> _cards = new();
    private AmsBuiState? _state;
    private string? _hint;
    private Color? _barColor;

    public AmsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HeaderPanel.PanelOverride = Flat(PanelBg, Border, new Thickness(1));
        SamplePanel.PanelOverride = Flat(PanelBg, Border, new Thickness(1));
        ChargeBar.BackgroundStyleBoxOverride = Flat(PanelBg, Border, new Thickness(1));

        ActionButton.OnPressed += _ => OnLaunch?.Invoke();
    }

    private static StyleBoxFlat Flat(Color bg, Color? border = null, Thickness? thickness = null)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = bg,
            BorderColor = border ?? Color.Transparent,
            BorderThickness = thickness ?? new Thickness(0),
        };
    }

    private PartCard CreateCard(string id)
    {
        var sprite = _entMan.System<SpriteSystem>();

        var icon = new TextureRect
        {
            Texture = sprite.Frame0(new SpriteSpecifier.Rsi(new ResPath(PartsRsiPath), id.Replace("ams_part_", ""))),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            MinSize = new Vector2(36, 36),
            SetSize = new Vector2(36, 36),
            VerticalAlignment = VAlignment.Center,
        };

        var name = new Label { Text = Loc.GetString(id.Replace('_', '-')), ClipText = true };

        var state = new Label { ClipText = true };
        state.StyleClasses.Add("LabelSubText");

        var progress = new ProgressBar
        {
            MinValue = 0,
            MaxValue = 1,
            MinHeight = 5,
            Margin = new Thickness(0, 3, 0, 0),
            BackgroundStyleBoxOverride = Flat(PanelBg),
        };

        var texts = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        texts.AddChild(name);
        texts.AddChild(state);
        texts.AddChild(progress);

        var lever = new Button
        {
            ToggleMode = true,
            MinWidth = 58,
            MinHeight = 28,
            VerticalAlignment = VAlignment.Center,
            ToolTip = Loc.GetString("ams-ui-lever-tooltip"),
        };
        lever.OnPressed += _ => OnLever?.Invoke(id);

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(8, 6, 6, 6),
            SeparationOverride = 8,
        };
        row.AddChild(icon);
        row.AddChild(texts);
        row.AddChild(lever);

        var panel = new PanelContainer { HorizontalExpand = true };
        panel.AddChild(row);
        PartsGrid.AddChild(panel);

        return new PartCard(panel, state, progress, lever);
    }

    public void UpdateState(AmsBuiState state)
    {
        _state = state;
        var editable = state.Status == AmsStatus.Inactive;
        var ready = 0;

        foreach (var part in state.Parts)
        {
            if (!_cards.TryGetValue(part.Slot, out var card))
                _cards[part.Slot] = card = CreateCard(part.Slot);

            string text;
            Color color;
            var progress = 1f;

            if (!part.Installed)
            {
                text = Loc.GetString("ams-ui-part-missing");
                color = Neutral;
                progress = 0f;
            }
            else if (!part.Secured)
            {
                text = Loc.GetString("ams-ui-part-reinforce", ("material", part.Material ?? "?"),
                    ("done", part.Done), ("needed", part.Needed));
                color = Warning;
                progress = part.Needed > 0 ? (float) part.Done / part.Needed : 1f;
            }
            else if (!part.Lever)
            {
                text = Loc.GetString("ams-ui-part-secured");
                color = Info;
            }
            else
            {
                text = Loc.GetString("ams-ui-part-ready");
                color = Good;
                ready++;
            }

            card.State.Text = text;
            card.State.FontColorOverride = color;
            card.State.ToolTip = text;
            card.Progress.Value = progress;

            card.Lever.Pressed = part.Lever;
            card.Lever.Disabled = !(editable && part.Secured);
            card.Lever.Text = Loc.GetString(part.Lever ? "ams-ui-lever-on" : "ams-ui-lever-off");

            if (card.Color != color)
            {
                card.Color = color;
                card.Panel.PanelOverride = Flat(CardBg, color.WithAlpha(0.8f), new Thickness(3, 0, 0, 0));
                card.Progress.ForegroundStyleBoxOverride = Flat(color);
            }
        }

        PartsCountLabel.Text = Loc.GetString("ams-ui-parts-ready", ("ready", ready), ("total", state.Parts.Count));

        SamplePanel.Visible = state.RequireSample;
        if (state.RequireSample)
        {
            var locked = state.Status != AmsStatus.Inactive;
            SampleLabel.Text = Loc.GetString(locked ? "ams-ui-sample-locked"
                : state.SampleInPlace ? "ams-ui-sample-in-place" : "ams-ui-sample-missing");
            var color = locked || state.SampleInPlace ? Good : state.Primed ? Info : Neutral;
            SampleLabel.FontColorOverride = color;
        }

        var key = state.Status.ToString().ToLowerInvariant();
        var statusColor = StatusColor(state.Status);
        StatusLabel.Text = Loc.GetString($"ams-ui-status-{key}");
        StatusLabel.FontColorOverride = statusColor;

        TimerCaption.Text = state.Status switch
        {
            AmsStatus.Synchronizing => Loc.GetString("ams-ui-timer-synchronizing"),
            AmsStatus.Active => Loc.GetString("ams-ui-timer-active"),
            AmsStatus.Detonating => Loc.GetString("ams-ui-timer-detonating"),
            _ => string.Empty,
        };

        if (_barColor != statusColor)
        {
            _barColor = statusColor;
            ChargeBar.ForegroundStyleBoxOverride = Flat(statusColor);
        }

        SetHint(Loc.GetString(state.Status == AmsStatus.Inactive ? InactiveHint(state) : $"ams-ui-hint-{key}"));

        if (state.Status == AmsStatus.Inactive)
        {
            ActionButton.Text = Loc.GetString(InactiveButton(state));
            ActionButton.Disabled = !(state.Primed && !state.RequireSample);
        }
        else
        {
            ActionButton.Text = Loc.GetString($"ams-ui-btn-{key}");
            ActionButton.Disabled = true;
        }
    }

    private void SetHint(string text)
    {
        if (_hint == text)
            return;

        _hint = text;
        var msg = new FormattedMessage();
        msg.PushColor(Neutral);
        msg.AddText(text);
        msg.Pop();
        HintLabel.SetMessage(msg);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state is not { } s)
            return;

        var now = _timing.CurTime;

        TimeSpan? remaining = s.Status switch
        {
            AmsStatus.Synchronizing when s.SyncStartTime is { } start => start + TimeSpan.FromSeconds(s.ChargeTime) - now,
            AmsStatus.Active => s.ActiveEndTime - now,
            AmsStatus.Detonating => s.DetonationTime - now,
            _ => null,
        };

        if (remaining is { } r)
        {
            if (r < TimeSpan.Zero)
                r = TimeSpan.Zero;

            TimerLabel.Text = $"{(int) r.TotalMinutes:00}:{r.Seconds:00}";
            TimerLabel.FontColorOverride = StatusColor(s.Status);
        }
        else
        {
            TimerLabel.Text = string.Empty;
        }

        var charge = AmsHelpers.GetCharge(s.Status, s.SyncStartTime, s.ChargeTime, now);
        ChargeBar.Value = charge;
        ChargeLabel.Text = $"{(int) (charge * 100)}%";
    }

    private static string InactiveButton(AmsBuiState s)
    {
        if (s.Parts.Exists(p => !p.Installed))
            return "ams-ui-btn-need-parts";
        if (s.Parts.Exists(p => !p.Secured))
            return "ams-ui-btn-need-reinforce";
        if (s.Parts.Exists(p => !p.Lever))
            return "ams-ui-btn-need-levers";
        return s.RequireSample ? "ams-ui-btn-need-sample" : "ams-ui-btn-start-sync";
    }

    private static string InactiveHint(AmsBuiState s)
    {
        if (s.Parts.Exists(p => !p.Installed))
            return "ams-ui-hint-inactive";
        if (s.Parts.Exists(p => !p.Secured))
            return "ams-ui-hint-reinforce";
        if (s.Parts.Exists(p => !p.Lever))
            return "ams-ui-hint-levers";
        return s.RequireSample ? "ams-ui-hint-sample" : "ams-ui-hint-primed";
    }

    private static Color StatusColor(AmsStatus status) => status switch
    {
        AmsStatus.Synchronizing => Info,
        AmsStatus.Ready or AmsStatus.Active => Good,
        AmsStatus.Detonating or AmsStatus.Destroyed => Danger,
        _ => Neutral,
    };
}
