using Content.Client.UserInterface.Systems.Viewport;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._BlackM.Rules;

[GenerateTypedNameReferences]
public sealed partial class RulesScreenSetup : Control
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IUserInterfaceManager _ui = default!;
    private readonly int _originalWidth;
    private readonly int _originalScale;
    private readonly bool _originalStretch;
    private bool _updating;
    private bool _finished;

    public event Action? OnSettingsChanged;
    public event Action? OnContinuePressed;
    public event Action? OnSkipPressed;

    public RulesScreenSetup()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        _originalWidth = _cfg.GetCVar(CCVars.ViewportWidth);
        _originalScale = _cfg.GetCVar(CCVars.ViewportFixedScaleFactor);
        _originalStretch = _cfg.GetCVar(CCVars.ViewportStretch);
        SettingsPanel.PanelOverride = new StyleBoxFlat(Color.FromHex("#191D20F5"))
        {
            BorderColor = Color.FromHex("#BEA16C"),
            BorderThickness = new Thickness(1, 3, 1, 1),
        };
        Introduction.SetMessage(Loc.GetString("blackm-screen-setup-intro"));
        UpdateWidthRange(0);
        UpdateControls();

        FullHdButton.OnPressed += _ => Apply(20, 3);
        TwoKButton.OnPressed += _ => Apply(21, 4);
        ScaleSlider.OnValueChanged += _ => ApplySliders();
        WidthSlider.OnValueChanged += _ => ApplySliders();
        ContinueButton.OnPressed += _ => Continue();
        SkipButton.OnPressed += _ => Skip();
        _cfg.OnValueChanged(CCVars.ViewportMinimumWidth, UpdateWidthRange);
        _cfg.OnValueChanged(CCVars.ViewportMaximumWidth, UpdateWidthRange);
    }

    private void UpdateWidthRange(int value)
    {
        _updating = true;
        WidthSlider.MaxValue = _cfg.GetCVar(CCVars.ViewportMaximumWidth);
        WidthSlider.MinValue = _cfg.GetCVar(CCVars.ViewportMinimumWidth);
        WidthSlider.Disabled = WidthSlider.MinValue == WidthSlider.MaxValue;
        FullHdButton.Disabled = 20 < WidthSlider.MinValue || 20 > WidthSlider.MaxValue;
        TwoKButton.Disabled = 21 < WidthSlider.MinValue || 21 > WidthSlider.MaxValue;
        _updating = false;
        UpdateControls();
        OnSettingsChanged?.Invoke();
    }

    private void UpdateControls()
    {
        var width = _cfg.GetCVar(CCVars.ViewportWidth);
        var scale = _cfg.GetCVar(CCVars.ViewportFixedScaleFactor);
        var stretch = _cfg.GetCVar(CCVars.ViewportStretch);
        WidthSlider.SetValueWithoutEvent(width);
        ScaleSlider.SetValueWithoutEvent(scale);
        WidthValue.Text = ((int) WidthSlider.Value).ToString();
        ScaleValue.Text = Loc.GetString("blackm-screen-setup-scale-value", ("scale", scale));
        FullHdButton.Pressed = !stretch && width == 20 && scale == 3;
        TwoKButton.Pressed = !stretch && width == 21 && scale == 4;
    }

    private void ApplySliders()
    {
        if (!_updating)
            Apply((int) WidthSlider.Value, (int) ScaleSlider.Value);
    }

    private void Apply(int width, int scale)
    {
        if (_finished)
            return;
        // Fixed scale is ignored by the normal game viewport while stretching is enabled.
        _cfg.SetCVar(CCVars.ViewportStretch, false);
        _cfg.SetCVar(CCVars.ViewportFixedScaleFactor, scale);
        _cfg.SetCVar(CCVars.ViewportWidth, Math.Clamp(width, (int) WidthSlider.MinValue, (int) WidthSlider.MaxValue));
        _ui.GetUIController<ViewportUIController>().ReloadViewport();
        UpdateControls();
        OnSettingsChanged?.Invoke();
    }

    private void Continue()
    {
        if (_finished)
            return;
        _cfg.SaveToFile();
        _finished = true;
        OnContinuePressed?.Invoke();
    }

    private void Skip()
    {
        if (_finished)
            return;
        RestoreSettings();
        _finished = true;
        OnSkipPressed?.Invoke();
    }

    private void RestoreSettings()
    {
        _cfg.SetCVar(CCVars.ViewportStretch, _originalStretch);
        _cfg.SetCVar(CCVars.ViewportFixedScaleFactor, _originalScale);
        _cfg.SetCVar(CCVars.ViewportWidth, _originalWidth);
        _ui.GetUIController<ViewportUIController>().ReloadViewport();
    }

    protected override void Resized()
    {
        base.Resized();
        if (SettingsPanel == null)
            return;
        SettingsPanel.SetWidth = Math.Min(480, Math.Max(1, Width - 48));
        SettingsPanel.MaxHeight = Math.Max(1, Height - 48);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _cfg.UnsubValueChanged(CCVars.ViewportMinimumWidth, UpdateWidthRange);
            _cfg.UnsubValueChanged(CCVars.ViewportMaximumWidth, UpdateWidthRange);
            if (!_finished)
                RestoreSettings();
            OnSettingsChanged = null;
            OnContinuePressed = null;
            OnSkipPressed = null;
        }
        base.Dispose(disposing);
    }
}
