    public SecurityCommandWindow(SecurityCommandClientSystem system)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _system = system;

        AddIcon(ToggleSidebarButton, SecurityCommandSprites.UiSidebar, 16);
        AddIcon(RefreshGridsButton, SecurityCommandSprites.UiRefresh, 16);
        AddIcon(CenterMeButton, SecurityCommandSprites.UiCenter, 16);

        AddIcon(CreateSquadButton, SecurityCommandSprites.UiPlus, 14);
        SetIconText(ClearOrdersButton, SecurityCommandSprites.UiDelete, Loc.GetString("security-command-orders-clear"));
        SquadCreatePanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#151a1f"),
            BorderColor = CardBorder,
            BorderThickness = new Thickness(1),
        };

        SetIconText(FinishButton, SecurityCommandSprites.UiFinish, Loc.GetString("security-command-finish"));
        SetIconText(CancelButton, SecurityCommandSprites.UiClose, Loc.GetString("security-command-cancel"));

        _map = new SecurityTacticalMapControl(_system)
        {
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        MapPanel.AddChild(_map);

        _map.OfficerClicked += OpenOfficerMenu;
        _map.ContextRequested += OpenContextMenu;
        OnClose += () =>
        {
            CloseContextMenu();
            OrderTextError.Visible = false;
        };

        ToggleSidebarButton.OnPressed += _ => LeftPanel.Visible = ToggleSidebarButton.Pressed;
        TabOfficersButton.OnPressed += _ => SetPage(SidebarPage.Officers);
        TabSquadsButton.OnPressed += _ => SetPage(SidebarPage.Squads);
        TabOrdersButton.OnPressed += _ => SetPage(SidebarPage.Orders);

        GridOption.OnItemSelected += args =>
        {
            GridOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _grids.Count)
                _map.SetGrid(_grids[args.Id]);
        };
        RefreshGridsButton.OnPressed += _ => RefreshGrids();
        CenterMeButton.OnPressed += _ => _map.CenterOnLocal();

        RefreshGrids();

        OrderText.IsValid = text => text.Length <= SecurityCommandConstants.MaxTextLength;
        OrderText.OnTextChanged += _ => OrderTextError.Visible = false;
        SquadNameEdit.IsValid = text => text.Length <= SecurityCommandConstants.MaxSquadNameLength;
        PostDurationInput.IsValid = value => value is >= 0 and <= SecurityCommandConstants.MaxPostDurationMinutes;
        PostDurationInput.InitDefaultButtons();
        PostDurationInput.ValueChanged += _ => _system.SetPostDuration(PostDurationInput.Value);

        BuildSwatches(ColorButtons, _colorButtons, _colorIndex, index =>
        {
            _colorIndex = index;
            UpdatePlacement();
        });
        BuildSwatches(SquadColorButtons, _squadColorButtons, _squadColorIndex, index => _squadColorIndex = index);
        BuildTools();

        TargetOption.OnItemSelected += args =>
        {
            TargetOption.SelectId(args.Id);
            if (_targets.TryGetValue(args.Id, out var target))
                _selectedTarget = target;
            SyncMapSelection();
            RefreshLists();
        };

        CreateSquadButton.OnPressed += _ => CreateSquad();
        SquadNameEdit.OnTextEntered += _ => CreateSquad();

        ClearOrdersButton.OnPressed += _ => _system.ClearOrders();
        FinishButton.OnPressed += _ =>
        {
            if (_system.FinishPlacement())
                return;

            PlacementHint.Text = Loc.GetString("security-command-hint-route-need-points");
            PlacementHint.FontColorOverride = ErrorText;
        };
        CancelButton.OnPressed += _ => _system.CancelPlacement();

        _system.StateUpdated += OnStateUpdated;
        _system.PlacementChanged += UpdatePlacement;

        SetPage(SidebarPage.Officers);
        OnStateUpdated();
        UpdatePlacement();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        _officerPopup?.Close();
        _system.StateUpdated -= OnStateUpdated;
        _system.PlacementChanged -= UpdatePlacement;
    }

    protected override void Opened()
    {
        base.Opened();
        RefreshGrids();
        FitToScreen();
    }

    private void FitToScreen()
    {
        var commander = _commanderMode != false;
        var preferred = commander ? new Vector2(1280, 780) : new Vector2(820, 720);
        var minimum = commander ? new Vector2(980, 620) : new Vector2(560, 480);
        var available = UserInterfaceManager.WindowRoot.Size - new Vector2(24f);
        if (available.X <= 0 || available.Y <= 0)
            available = preferred;

        MinSize = Vector2.Min(minimum, available);
        MaxSize = available;
        SetSize = Vector2.Min(preferred, available);
        LeftPanel.SetWidth = Math.Clamp(SetSize.X * 0.28f, 260f, 360f);
        Measure(SetSize);
    }

    private void SetPage(SidebarPage page)
    {
        _page = page;

        OfficersPage.Visible = page == SidebarPage.Officers;
        SquadsPage.Visible = page == SidebarPage.Squads;
        OrdersPage.Visible = page == SidebarPage.Orders;

        TabOfficersButton.Pressed = page == SidebarPage.Officers;
        TabSquadsButton.Pressed = page == SidebarPage.Squads;
        TabOrdersButton.Pressed = page == SidebarPage.Orders;
    }

    private void ApplyMode(bool commander)
    {
        if (_commanderMode == commander)
            return;

        _commanderMode = commander;

        LeftPanel.Visible = commander && ToggleSidebarButton.Pressed;
        ToggleSidebarButton.Visible = commander;
        OrderBar.Visible = commander;

        Title = Loc.GetString(commander ? "security-command-window-title" : "security-command-viewer-title");
        if (IsOpen)
        {
            FitToScreen();
            RecenterWindow(new Vector2(0.25f, 0.5f));
        }

        if (!commander)
        {
            _system.CancelPlacement();
            CloseContextMenu();
            _map.SelectedOfficer = null;
            _map.SelectedSquad = null;
        }
    }

    private bool IsCommanderView => _system.State?.IsCommander == true;

    private void RefreshGrids()
    {
        var current = _map.MapUid;
        EntityUid? local = null;
        if (_player.LocalEntity is { } player && _entMan.TryGetComponent(player, out TransformComponent? xform))
            local = xform.GridUid;

        _grids.Clear();
        GridOption.Clear();

        var query = _entMan.EntityQueryEnumerator<NavMapComponent, MetaDataComponent>();
        while (query.MoveNext(out var uid, out _, out var meta))
        {
            GridOption.AddItem(meta.EntityName, _grids.Count);
            _grids.Add(uid);
        }

        if (_grids.Count == 0)
        {
            GridOption.AddItem(Loc.GetString("security-command-map-grid-none"), -1);
            GridOption.Disabled = true;
            _map.SetGrid(null);
            return;
        }

        GridOption.Disabled = _grids.Count == 1;

        var index = -1;
        if (current != null)
            index = _grids.IndexOf(current.Value);
        if (index < 0 && local != null)
            index = _grids.IndexOf(local.Value);
        if (index < 0)
            index = 0;

        GridOption.SelectId(index);
        _map.SetGrid(_grids[index]);
    }

    private void BuildSwatches(BoxContainer parent, List<Button> buttons, int selected, Action<int> onSelect)
    {
        for (var i = 0; i < SecurityCommandConstants.Palette.Length; i++)
        {
            var index = i;
            var (loc, color) = SecurityCommandConstants.Palette[i];
            var button = new Button
            {
                ToggleMode = true,
                SetSize = new Vector2(24, 24),
                ToolTip = Loc.GetString(loc),
                Pressed = i == selected,
                StyleClasses = { "ButtonSquare" },
            };

            button.AddChild(new PanelContainer
            {
                Margin = new Thickness(1),
                PanelOverride = new StyleBoxFlat { BackgroundColor = color },
            });

            button.OnPressed += _ =>
            {
                for (var j = 0; j < buttons.Count; j++)
                {
                    buttons[j].Pressed = j == index;
                }

                onSelect(index);
            };

            buttons.Add(button);
            parent.AddChild(button);
        }
    }

    private static void SelectSwatch(List<Button> buttons, int index)
    {
        for (var j = 0; j < buttons.Count; j++)
        {
            buttons[j].Pressed = j == index;
        }
    }

    private void BuildTools()
    {
        foreach (var type in Tools)
        {
            var key = SecurityCommandConstants.GetTypeLoc(type);
            var caption = type switch
            {
                SecurityOrderType.Move => "security-command-tool-move",
                SecurityOrderType.Post => "security-command-tool-post",
                SecurityOrderType.PatrolRoute => "security-command-tool-route",
                SecurityOrderType.PatrolZone => "security-command-tool-zone",
                _ => key,
            };
            var button = new Button
            {
                Text = Loc.GetString(caption),
                TextAlign = Label.AlignMode.Center,
                ToolTip = Loc.GetString(key + "-desc"),
                ToggleMode = true,
                MuteSounds = true,
                HorizontalExpand = true,
                MinWidth = 82,
                MinHeight = 34,
            };

            button.OnPressed += _ => OnToolPressed(type);
            _toolButtons[type] = button;
            ToolRow.AddChild(button);
        }
    }

    private void OnToolPressed(SecurityOrderType type)
    {
        if (_system.PlacingType == type)
        {
            _system.CancelPlacement();
            return;
        }

        if (!TryMakeDraft(type, out var draft))
        {
            UpdatePlacement();
            return;
        }

        _system.StartPlacement(type, draft);
    }

    private bool TryMakeDraft(SecurityOrderType type, out SecurityOrderDraft draft)
    {
        var text = SecurityCommandConstants.SanitizeText(OrderText.Text, SecurityCommandConstants.MaxTextLength);
        var color = SecurityCommandConstants.Palette[_colorIndex].Color;
        draft = new SecurityOrderDraft(
            _selectedTarget.Kind,
            _selectedTarget.SquadId,
            _selectedTarget.Officer,
            text,
            color,
            type == SecurityOrderType.Post ? PostDurationInput.Value : 0);

        if (SecurityCommandConstants.RequiresText(type) && text.Length == 0)
        {
            OrderTextError.Visible = true;
            OrderText.GrabKeyboardFocus();
            return false;
        }

        OrderTextError.Visible = false;
        return true;
    }

    private void CreateSquad()
    {
        if (_system.State is { } state && state.Squads.Count >= SecurityCommandConstants.MaxSquads)
            return;

        var color = SecurityCommandConstants.Palette[Math.Clamp(_squadColorIndex, 0, SecurityCommandConstants.Palette.Length - 1)].Color;
        _system.CreateSquad(SquadNameEdit.Text, color);
        SquadNameEdit.Text = string.Empty;

        _squadColorIndex = (_squadColorIndex + 1) % SecurityCommandConstants.Palette.Length;
        SelectSwatch(_squadColorButtons, _squadColorIndex);
    }

    private void UpdatePlacement()
    {
        var type = _system.PlacingType;

        foreach (var (toolType, button) in _toolButtons)
        {
            button.Pressed = toolType == type;
        }

        PlacementPanel.Visible = type != null;
        FinishButton.Visible = type == SecurityOrderType.PatrolRoute;
        PostTimerBox.Visible = type == SecurityOrderType.Post;
        if (type == null)
            return;

        PlacementPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#0d1013"),
            BorderColor = _system.Draft.Color,
            BorderThickness = new Thickness(3, 0, 0, 0),
        };
        PlacementIcon.Texture = _system.GetIcon(SecurityCommandSprites.Order(type.Value));
        PlacementIcon.ModulateSelfOverride = _system.Draft.Color;
        PlacementHint.FontColorOverride = Color.White;
        PlacementHint.Text = SecurityCommandClientSystem.GetTypeName(type.Value) + "  ·  " + type switch
        {
            SecurityOrderType.PatrolRoute => Loc.GetString("security-command-hint-route",
                ("count", _system.PendingPoints.Count), ("max", SecurityCommandConstants.MaxRoutePoints)),
            SecurityOrderType.Post => Loc.GetString("security-command-hint-post",
                ("count", _system.PendingPoints.Count)),
            SecurityOrderType.PatrolZone => Loc.GetString("security-command-hint-zone",
                ("count", _system.PendingPoints.Count)),
            _ => Loc.GetString("security-command-hint-point"),
        };
    }

    internal void OpenOfficerMenu(SecurityOfficerData officer)
    {
        if (!IsOpen || !IsCommanderView)
            return;

        CloseContextMenu();
        var content = CreateMenuContent();
        BuildOfficerMenu(content, officer);
        var panel = new PanelContainer
        {
            MouseFilter = MouseFilterMode.Stop,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = CardBack,
                BorderColor = Accent,
                BorderThickness = new Thickness(1),
            },
        };
        panel.AddChild(content);
        var popup = new Popup();
        popup.AddChild(panel);
        popup.OnPopupHide += () => _officerPopup = null;
        _officerPopup = popup;
        popup.OpenAtMouse();
    }

    private void CloseContextMenu()
    {
        _officerPopup?.Close();
        _map.CloseMenu();
    }

    private void SelectOfficerTarget(SecurityOfficerData officer)
    {
        SelectTarget(new TargetEntry(SecurityOrderTargetKind.Officer, 0, officer.Entity));
    }

    private void OpenContextMenu(SecurityMapContext context)
    {
        if (!IsCommanderView)
        {
            if (context.Order is { } viewed)
                _map.CenterOnOrder(viewed);
            return;
        }

        var box = CreateMenuContent();

        if (context.Order is { } order)
            BuildOrderMenu(box, order);
        else if (context.Officer is { } officer)
            BuildOfficerMenu(box, officer);
        else if (context.Coordinates is { } coords)
            BuildPointMenu(box, coords);
        else
            return;

        CloseContextMenu();
        _map.OpenMenu(box, context.PixelPosition);
    }

    private static BoxContainer CreateMenuContent() => new()
    {
        Orientation = BoxContainer.LayoutOrientation.Vertical,
        SeparationOverride = 2,
        Margin = new Thickness(6),
        MinWidth = 220,
    };

    private void BuildOrderMenu(BoxContainer box, SecurityOrderData order)
    {
        box.AddChild(MenuHeader(SecurityCommandSprites.Order(order.Type), SecurityCommandClientSystem.GetDisplayText(order),
            order.Color, true));
        box.AddChild(MenuSubLabel(_system.DescribeTarget(order)));
        if (order.PostDurationMinutes > 0)
            box.AddChild(MenuSubLabel(Loc.GetString("security-command-post-duration", ("minutes", order.PostDurationMinutes))));
        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });

        box.AddChild(MenuButton(Loc.GetString("security-command-menu-show"), () => _map.CenterOnOrder(order),
            icon: SecurityCommandSprites.UiShow));
        box.AddChild(MenuButton(Loc.GetString("security-command-menu-cancel-order"), () => _system.RemoveOrder(order.Id),
            icon: SecurityCommandSprites.UiClose, caution: true));
    }

    private void BuildOfficerMenu(BoxContainer box, SecurityOfficerData officer)
    {
        var squad = _system.GetSquad(officer.SquadId);
        box.AddChild(MenuHeader(SecurityCommandSprites.ForOfficer(officer), officer.Name, squad?.Color ?? Color.White, false));
        box.AddChild(MenuSubLabel($"{officer.Job} · {Loc.GetString(GetStatusLoc(officer.Status))}"));
        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });

        if (_system.State is { } state && state.Squads.Count > 0)
        {
            box.AddChild(MenuSubLabel(Loc.GetString("security-command-menu-squad")));
            var entity = officer.Entity;
            box.AddChild(MenuButton(Mark(officer.SquadId == 0) + Loc.GetString("security-command-squad-none"),
                () => _system.AssignOfficer(entity, 0), color: Color.FromHex("#444444")));

            foreach (var s in state.Squads)
            {
                var squadId = s.Id;
                box.AddChild(MenuButton(Mark(officer.SquadId == squadId) + s.Name,
                    () => _system.AssignOfficer(entity, squadId), color: s.Color));
            }

            box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });
        }

        if (officer.Status != SecurityOfficerStatus.Dead)
        {
            box.AddChild(MenuButton(Loc.GetString("security-command-menu-order-personal"),
                () => SelectOfficerTarget(officer), icon: SecurityCommandSprites.UiTarget));
        }

        if (squad != null)
        {
            var squadId = squad.Id;
            box.AddChild(MenuButton(Loc.GetString("security-command-menu-order-squad", ("name", squad.Name)),
                () => SelectTarget(new TargetEntry(SecurityOrderTargetKind.Squad, squadId, null)),
                icon: SecurityCommandSprites.UiSidebar, color: squad.Color));
        }

        box.AddChild(MenuButton(Loc.GetString("security-command-menu-show"), () =>
        {
            if (_system.TryGetOfficerPosition(officer.Entity, out var pos))
                _map.CenterOn(pos);
        }, icon: SecurityCommandSprites.UiShow));
    }

    private void BuildPointMenu(BoxContainer box, EntityCoordinates coords)
    {
        var color = SecurityCommandConstants.Palette[_colorIndex].Color;
        box.AddChild(MenuHeader(SecurityCommandSprites.UiTarget, Loc.GetString("security-command-menu-order-here"), color, true));
        box.AddChild(MenuSubLabel(Loc.GetString("security-command-menu-target", ("target", DescribeSelectedTarget()))));
        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });

        var hasText = SecurityCommandConstants.SanitizeText(OrderText.Text, SecurityCommandConstants.MaxTextLength).Length > 0;

        foreach (var type in Tools)
        {
            var orderType = type;
            var name = SecurityCommandClientSystem.GetTypeName(type);
            if (type is SecurityOrderType.PatrolRoute or SecurityOrderType.PatrolZone or SecurityOrderType.Post)
                name = Loc.GetString("security-command-menu-start-from", ("type", name));

            var button = MenuButton(name, () => StartFromPoint(orderType, coords));

            if (SecurityCommandConstants.RequiresText(type) && !hasText)
            {
                button.Disabled = true;
                button.ToolTip = Loc.GetString("security-command-hint-need-text");
            }

            box.AddChild(button);
        }

        if (_system.State is { Orders.Count: > 0 })
        {
            box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });
            box.AddChild(MenuButton(Loc.GetString("security-command-menu-clear-all"), () => _system.ClearOrders(),
                icon: SecurityCommandSprites.UiDelete, caution: true));
        }
    }

    private void StartFromPoint(SecurityOrderType type, EntityCoordinates coords)
    {
        if (!TryMakeDraft(type, out var draft))
            return;

        _system.StartPlacement(type, draft);
        _system.AddMapPoint(coords);
    }

    private static string Mark(bool active)
    {
        return active ? "✓ " : "   ";
    }

    private BoxContainer MenuHeader(SpriteSpecifier icon, string text, Color color, bool tintIcon)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(2, 0, 2, 2),
        };
        row.AddChild(Icon(icon, tintIcon ? color : Color.White, 18));
        row.AddChild(new Label
        {
            Text = text,
            FontColorOverride = color,
            ClipText = true,
            MaxWidth = 260,
            VerticalAlignment = VAlignment.Center,
        });
        return row;
    }

    private static Label MenuSubLabel(string text)
    {
        return new Label
        {
            Text = text,
            StyleClasses = { "LabelSubText" },
            ClipText = true,
            MaxWidth = 280,
            Margin = new Thickness(2, 0),
        };
    }

    private Button MenuButton(string text, Action action, SpriteSpecifier? icon = null, Color? color = null,
        bool caution = false)
    {
        var button = new Button
        {
            HorizontalExpand = true,
            MinHeight = 26,
        };

        if (caution)
            button.StyleClasses.Add("Caution");

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };

        if (icon != null)
            content.AddChild(Icon(icon, color ?? Color.White, 16));
        else if (color != null)
            content.AddChild(Swatch(color.Value, 12));

        content.AddChild(new Label { Text = text, VerticalAlignment = VAlignment.Center, ClipText = true, HorizontalExpand = true });
        button.AddChild(content);

        button.OnPressed += _ =>
        {
            CloseContextMenu();
            action();
        };

        return button;
    }

    private void OnStateUpdated()
    {
        var state = _system.State;
        if (state == null)
            return;

        ApplyMode(state.IsCommander);

        TabOfficersButton.Text = TabTitle("security-command-tab-officers", state.Officers.Count);
        TabSquadsButton.Text = TabTitle("security-command-tab-squads", state.Squads.Count);
        TabOrdersButton.Text = TabTitle("security-command-tab-orders", state.Orders.Count);

        RebuildTargets(state);
        RefreshLists();

        var squadsFull = state.Squads.Count >= SecurityCommandConstants.MaxSquads;
        CreateSquadButton.Disabled = squadsFull;
        SquadNameEdit.Editable = !squadsFull;
        ClearOrdersButton.Disabled = state.Orders.Count == 0;
    }

    private void RefreshLists()
    {
        if (_system.State is not { } state)
            return;

        RebuildOfficers(state);
        RebuildSquads(state);
        RebuildOrders(state);
    }

    private static string TabTitle(string loc, int count)
    {
        return Loc.GetString("security-command-tab-count", ("name", Loc.GetString(loc)), ("count", count));
    }

    private void RebuildTargets(SecurityCommandStateMessage state)
    {
        TargetOption.Clear();
        _targets.Clear();

        var id = 0;
        var selectedId = 0;

        void Add(string label, TargetEntry entry)
        {
            TargetOption.AddItem(label, id);
            _targets[id] = entry;
            if (entry == _selectedTarget)
                selectedId = id;
            id++;
        }

        Add(Loc.GetString("security-command-target-all"), new TargetEntry(SecurityOrderTargetKind.All, 0, null));

        foreach (var squad in state.Squads)
        {
            Add(Loc.GetString("security-command-target-squad", ("name", squad.Name)),
                new TargetEntry(SecurityOrderTargetKind.Squad, squad.Id, null));
        }

        foreach (var officer in state.Officers)
        {
            if (officer.Status == SecurityOfficerStatus.Dead)
                continue;

            Add(Loc.GetString("security-command-target-officer", ("name", officer.Name)),
                new TargetEntry(SecurityOrderTargetKind.Officer, 0, officer.Entity));
        }

        if (!_targets.TryGetValue(selectedId, out var selected) || selected != _selectedTarget)
            _selectedTarget = _targets[0];

        TargetOption.SelectId(selectedId);
        SyncMapSelection();
    }

    private void SyncMapSelection()
    {
        _map.SelectedOfficer = _selectedTarget.Kind == SecurityOrderTargetKind.Officer ? _selectedTarget.Officer : null;
        _map.SelectedSquad = _selectedTarget.Kind == SecurityOrderTargetKind.Squad ? _selectedTarget.SquadId : null;
    }

    private string DescribeSelectedTarget()
    {
        switch (_selectedTarget.Kind)
        {
            case SecurityOrderTargetKind.Squad:
                var squad = _system.GetSquad(_selectedTarget.SquadId);
                return squad != null
                    ? Loc.GetString("security-command-target-squad", ("name", squad.Name))
                    : Loc.GetString("security-command-target-all");
            case SecurityOrderTargetKind.Officer:
                if (_system.State is { } state)
                {
                    foreach (var officer in state.Officers)
                    {
                        if (officer.Entity == _selectedTarget.Officer)
                            return Loc.GetString("security-command-target-officer", ("name", officer.Name));
                    }
                }

                return Loc.GetString("security-command-target-all");
            default:
                return Loc.GetString("security-command-target-all");
        }
    }

    private void SelectTarget(TargetEntry entry)
    {
        foreach (var (id, target) in _targets)
        {
            if (target != entry)
                continue;

            TargetOption.SelectId(id);
            _selectedTarget = target;
            SyncMapSelection();
            RefreshLists();
            return;
        }
    }

    private bool IsSelected(SecurityOfficerData officer)
    {
        return _selectedTarget.Kind == SecurityOrderTargetKind.Officer && _selectedTarget.Officer == officer.Entity;
    }

    private bool IsSelected(SecuritySquadData squad)
    {
        return _selectedTarget.Kind == SecurityOrderTargetKind.Squad && _selectedTarget.SquadId == squad.Id;
    }

    private static int CompareOfficers(SecurityOfficerData a, SecurityOfficerData b)
    {
        var cmd = b.IsCommander.CompareTo(a.IsCommander);
        if (cmd != 0)
            return cmd;

        var status = StatusOrder(a.Status).CompareTo(StatusOrder(b.Status));
        return status != 0 ? status : string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase);
    }

    private static int StatusOrder(SecurityOfficerStatus status)
    {
        return status switch
        {
            SecurityOfficerStatus.Alive => 0,
            SecurityOfficerStatus.Critical => 1,
            SecurityOfficerStatus.Offline => 2,
            _ => 3,
        };
    }

    private void RebuildOfficers(SecurityCommandStateMessage state)
    {
        OfficersList.RemoveAllChildren();

        if (state.Officers.Count == 0)
        {
            OfficersList.AddChild(EmptyLabel("security-command-officers-empty"));
            return;
        }

        var officers = new List<SecurityOfficerData>(state.Officers);
        officers.Sort(CompareOfficers);
        var draftColor = SecurityCommandConstants.Palette[_colorIndex].Color;

        foreach (var officer in officers)
        {
            var squad = _system.GetSquad(officer.SquadId);
            var entity = officer.Entity;
            var offline = officer.Status == SecurityOfficerStatus.Offline;
            var dead = officer.Status == SecurityOfficerStatus.Dead;

            var card = Card(IsSelected(officer) ? draftColor : null);
            var body = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };
            card.AddChild(body);

            body.AddChild(Stripe(squad?.Color ?? Color.FromHex("#3a4048")));

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                HorizontalExpand = true,
                Margin = new Thickness(0, 5, 6, 5),
            };
            body.AddChild(column);

            var top = HBox(6);
            top.AddChild(Icon(SecurityCommandSprites.ForOfficer(officer), offline ? Color.White.WithAlpha(0.45f) : Color.White, 18));
            var officerButton = new Button
            {
                Text = officer.Name,
                TextAlign = Label.AlignMode.Left,
                ToolTip = Loc.GetString("security-command-map-officer-hint"),
                ClipText = true,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            officerButton.Label.FontColorOverride = offline || dead ? MutedText : null;
            officerButton.OnPressed += _ => OpenOfficerMenu(officer);
            top.AddChild(officerButton);

            if (officer.IsCommander)
                top.AddChild(Tag(Loc.GetString("security-command-officer-commander-tag"), Accent));

            top.AddChild(Tag(Loc.GetString(GetStatusLoc(officer.Status)), GetStatusColor(officer.Status)));
            column.AddChild(top);

            var bottom = HBox(4);
            bottom.AddChild(new Label
            {
                Text = officer.Job,
                StyleClasses = { "LabelSubText" },
                ClipText = true,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(24, 0, 0, 0),
            });

            var squadButton = new OptionButton { MinWidth = 120, ToolTip = Loc.GetString("security-command-menu-squad") };
            squadButton.AddItem(Loc.GetString("security-command-squad-none"), 0);
            foreach (var s in state.Squads)
            {
                squadButton.AddItem(s.Name, s.Id);
            }

            squadButton.SelectId(officer.SquadId);
            squadButton.OnItemSelected += args =>
            {
                squadButton.SelectId(args.Id);
                _system.AssignOfficer(entity, args.Id);
            };
            bottom.AddChild(squadButton);

            var showButton = IconButton(SecurityCommandSprites.UiShow, Loc.GetString("security-command-officer-show-desc"));
            showButton.Disabled = offline;
            showButton.OnPressed += _ =>
            {
                if (_system.TryGetOfficerPosition(entity, out var pos))
                    _map.CenterOn(pos);
            };
            bottom.AddChild(showButton);

            var targetButton = IconButton(SecurityCommandSprites.UiTarget, Loc.GetString("security-command-officer-order-desc"));
            targetButton.Disabled = dead;
            targetButton.ToggleMode = true;
            targetButton.Pressed = IsSelected(officer);
            var officerData = officer;
            targetButton.OnPressed += _ =>
            {
                if (IsSelected(officerData))
                    SelectTarget(new TargetEntry(SecurityOrderTargetKind.All, 0, null));
                else
                    SelectOfficerTarget(officerData);
            };
            bottom.AddChild(targetButton);

            column.AddChild(bottom);
            OfficersList.AddChild(card);
        }
    }

    private void RebuildSquads(SecurityCommandStateMessage state)
    {
        SquadsList.RemoveAllChildren();

        if (state.Squads.Count == 0)
        {
            SquadsList.AddChild(EmptyLabel("security-command-squads-empty"));
            return;
        }

        var names = new Dictionary<NetEntity, string>();
        foreach (var officer in state.Officers)
        {
            names[officer.Entity] = officer.Name;
        }

        var draftColor = SecurityCommandConstants.Palette[_colorIndex].Color;

        foreach (var squad in state.Squads)
        {
            var squadId = squad.Id;
            var selected = IsSelected(squad);
            var card = Card(selected ? draftColor : null);

            var body = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };
            card.AddChild(body);
            body.AddChild(Stripe(squad.Color));

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 3,
                HorizontalExpand = true,
                Margin = new Thickness(0, 5, 6, 5),
            };
            body.AddChild(column);

            var top = HBox(4);
            top.AddChild(new Label
            {
                Text = squad.Name,
                ClipText = true,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = squad.Color,
            });
            top.AddChild(Tag(Loc.GetString("security-command-squad-members", ("count", squad.Members.Count)), MutedText));

            var orderButton = IconButton(SecurityCommandSprites.UiTarget, Loc.GetString("security-command-squad-order"));
            orderButton.ToggleMode = true;
            orderButton.Pressed = selected;
            orderButton.OnPressed += _ =>
            {
                SelectTarget(IsSelectedSquadId(squadId)
                    ? new TargetEntry(SecurityOrderTargetKind.All, 0, null)
                    : new TargetEntry(SecurityOrderTargetKind.Squad, squadId, null));
            };
            top.AddChild(orderButton);

            var removeButton = IconButton(SecurityCommandSprites.UiDelete, Loc.GetString("security-command-squad-remove"));
            removeButton.MuteSounds = true;
            removeButton.StyleClasses.Add("Caution");
            removeButton.OnPressed += _ => _system.RemoveSquad(squadId);
            top.AddChild(removeButton);
            column.AddChild(top);

            var members = new List<string>();
            foreach (var member in squad.Members)
            {
                if (names.TryGetValue(member, out var name))
                    members.Add(name);
            }

            column.AddChild(new Label
            {
                Text = members.Count > 0
                    ? string.Join(", ", members)
                    : Loc.GetString("security-command-squad-members-none"),
                StyleClasses = { "LabelSubText" },
                ClipText = true,
                ToolTip = members.Count > 0 ? string.Join("\n", members) : null,
                MouseFilter = MouseFilterMode.Pass,
            });

            SquadsList.AddChild(card);
        }
    }

    private bool IsSelectedSquadId(int squadId)
    {
        return _selectedTarget.Kind == SecurityOrderTargetKind.Squad && _selectedTarget.SquadId == squadId;
    }

    private void RebuildOrders(SecurityCommandStateMessage state)
    {
        OrdersList.RemoveAllChildren();

        if (state.Orders.Count == 0)
        {
            OrdersList.AddChild(EmptyLabel("security-command-orders-empty"));
            return;
        }

        for (var i = state.Orders.Count - 1; i >= 0; i--)
        {
            var order = state.Orders[i];
            var orderId = order.Id;
            var orderData = order;

            var card = Card(null);
            var body = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Margin = new Thickness(6, 5),
            };
            card.AddChild(body);

            var iconBox = new PanelContainer
            {
                SetSize = new Vector2(32, 32),
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = order.Color.WithAlpha(0.18f),
                    BorderColor = order.Color,
                    BorderThickness = new Thickness(1),
                },
            };
            var icon = Icon(SecurityCommandSprites.Order(order.Type), order.Color, 18);
            icon.HorizontalAlignment = HAlignment.Center;
            iconBox.AddChild(icon);
            body.AddChild(iconBox);

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 1,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };

            var title = SecurityCommandClientSystem.GetTypeName(order.Type);
            if (!string.IsNullOrEmpty(order.Text))
                title += ": " + order.Text;

            column.AddChild(new Label { Text = title, ClipText = true });

            var minutes = Math.Max(0, (int) (_timing.CurTime - order.IssuedAt).TotalMinutes);
            column.AddChild(new Label
            {
                Text = _system.DescribeTarget(order) + "  ·  " + Loc.GetString("security-command-order-age", ("minutes", minutes)),
                StyleClasses = { "LabelSubText" },
                ClipText = true,
                ToolTip = Loc.GetString("security-command-order-issuer", ("name", order.IssuerName)),
                MouseFilter = MouseFilterMode.Pass,
            });
            if (order.PostDurationMinutes > 0)
            {
                column.AddChild(new Label
                {
                    Text = Loc.GetString("security-command-post-duration", ("minutes", order.PostDurationMinutes)),
                    StyleClasses = { "LabelSubText" },
                    ClipText = true,
                });
            }
            body.AddChild(column);

            var showButton = IconButton(SecurityCommandSprites.UiShow, Loc.GetString("security-command-order-show-desc"));
            showButton.VerticalAlignment = VAlignment.Center;
            showButton.OnPressed += _ => _map.CenterOnOrder(orderData);
            body.AddChild(showButton);

            var removeButton = IconButton(SecurityCommandSprites.UiClose, Loc.GetString("security-command-order-remove"));
            removeButton.MuteSounds = true;
            removeButton.VerticalAlignment = VAlignment.Center;
            removeButton.StyleClasses.Add("Caution");
            removeButton.OnPressed += _ => _system.RemoveOrder(orderId);
            body.AddChild(removeButton);

            OrdersList.AddChild(card);
        }
    }

    private void AddIcon(Button button, SpriteSpecifier icon, float size)
    {
        var rect = Icon(icon, Color.White, size);
        rect.HorizontalAlignment = HAlignment.Center;
        button.AddChild(rect);
    }

    private void SetIconText(Button button, SpriteSpecifier icon, string text)
    {
        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            HorizontalAlignment = HAlignment.Center,
        };
        content.AddChild(Icon(icon, Color.White, 14));
        content.AddChild(new Label { Text = text, VerticalAlignment = VAlignment.Center });
        button.AddChild(content);
    }

    private Button IconButton(SpriteSpecifier icon, string tooltip)
    {
        var button = new Button
        {
            MinSize = new Vector2(28, 26),
            ToolTip = tooltip,
        };
        AddIcon(button, icon, 14);
        return button;
    }

    private TextureRect Icon(SpriteSpecifier specifier, Color color, float size)
    {
        return new TextureRect
        {
            Texture = _system.GetIcon(specifier),
            ModulateSelfOverride = color,
            SetSize = new Vector2(size, size),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
        };
    }

    private static BoxContainer HBox(int separation)
    {
        return new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = separation,
        };
    }

    private static PanelContainer Card(Color? highlight)
    {
        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = highlight != null ? Color.InterpolateBetween(CardBack, highlight.Value, 0.08f) : CardBack,
                BorderColor = highlight ?? CardBorder,
                BorderThickness = new Thickness(1),
            },
        };
    }

    private static PanelContainer Stripe(Color color)
    {
        return new PanelContainer
        {
            MinWidth = 4,
            VerticalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
        };
    }

