    {
        return new PanelContainer
        {
            SetSize = new Vector2(size, size),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
        };
    }

    private static PanelContainer Tag(string text, Color color)
    {
        var tag = new PanelContainer
        {
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = color.WithAlpha(0.15f),
                BorderColor = color.WithAlpha(0.6f),
                BorderThickness = new Thickness(1),
