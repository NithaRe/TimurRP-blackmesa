        };
    }

    private static string GetStatusLoc(SecurityOfficerStatus status)
    {
        return status switch
        {
            SecurityOfficerStatus.Critical => "security-command-status-critical",
            SecurityOfficerStatus.Dead => "security-command-status-dead",
            SecurityOfficerStatus.Offline => "security-command-status-offline",
            _ => "security-command-status-alive",
        };
    }

    private static Color GetStatusColor(SecurityOfficerStatus status)
    {
        return status switch
        {
            SecurityOfficerStatus.Critical => Color.FromHex("#f0903a"),
            SecurityOfficerStatus.Dead => Color.FromHex("#e04a40"),
            SecurityOfficerStatus.Offline => Color.Gray,
            _ => Color.FromHex("#5bd35b"),
        };
    }
